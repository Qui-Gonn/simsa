namespace Tkd.Simsa.Domain.EventManagement;

/// <summary>
/// Enumeration for Taekwon-Do examination discipline categories (ITF terminology).
/// </summary>
public enum DisciplineType
{
    /// <summary>
    /// Pattern (Tul) demonstration
    /// </summary>
    PatternTul,

    /// <summary>
    /// Fundamental exercises
    /// </summary>
    FundamentalExercises,

    /// <summary>
    /// Step sparring
    /// </summary>
    StepSparring,

    /// <summary>
    /// Self-defense techniques
    /// </summary>
    SelfDefense,

    /// <summary>
    /// Sparring techniques and practice
    /// </summary>
    Sparring,

    /// <summary>
    /// Breaking techniques (board breaking)
    /// </summary>
    Breaking,

    /// <summary>
    /// Theoretical knowledge and terminology
    /// </summary>
    Theory
}
